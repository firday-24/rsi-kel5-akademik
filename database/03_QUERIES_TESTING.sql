-- QUERY PENGUJIAN. Jalankan di DBeaver setelah 01 dan 02 berhasil.
SET CURRENT SCHEMA PORTAL;

-- 1. Cek akun demo dan role.
SELECT ID_AKUN, EMAIL, PERAN, STATUS_AKUN FROM AKUN_PENGGUNA ORDER BY PERAN, EMAIL;

-- 2. Cek mahasiswa dan dosen PA.
SELECT M.NIM, M.NAMA_MAHASISWA, D.NAMA_DOSEN AS DOSEN_PA
FROM MAHASISWA M LEFT JOIN DOSEN_PA DP ON DP.NIM=M.NIM AND DP.TAHUN_AKADEMIK='2026/2027'
LEFT JOIN DOSEN D ON D.NIP=DP.NIP ORDER BY M.NIM;

-- 3. Rekap kehadiran per pengambilan mata kuliah. ID_PENGAMBILAN membedakan pengulangan.
SELECT K.NIM, KD.ID_PENGAMBILAN, MK.NAMA_MATKUL, JK.SEMESTER, JK.TAHUN_AKADEMIK,
 COUNT(P.ID_PRESENSI) AS TOTAL_PERTEMUAN,
 SUM(CASE WHEN P.STATUS_PRESENSI='HADIR' THEN 1 ELSE 0 END) AS HADIR,
 SUM(CASE WHEN P.STATUS_PRESENSI='IZIN' THEN 1 ELSE 0 END) AS IZIN,
 SUM(CASE WHEN P.STATUS_PRESENSI='SAKIT' THEN 1 ELSE 0 END) AS SAKIT,
 SUM(CASE WHEN P.STATUS_PRESENSI='ALPHA' THEN 1 ELSE 0 END) AS ALPHA
FROM KRS K JOIN KRS_DETAIL KD ON KD.ID_KRS=K.ID_KRS JOIN JADWAL_KULIAH JK ON JK.ID_JADWAL=KD.ID_JADWAL
JOIN MATA_KULIAH MK ON MK.ID_MATKUL=JK.ID_MATKUL LEFT JOIN PRESENSI P ON P.ID_PENGAMBILAN=KD.ID_PENGAMBILAN
GROUP BY K.NIM,KD.ID_PENGAMBILAN,MK.NAMA_MATKUL,JK.SEMESTER,JK.TAHUN_AKADEMIK ORDER BY K.NIM,KD.ID_PENGAMBILAN;

-- 4. Antrean pending khusus dosen pengampu. Ganti NIP jika ingin menguji dosen lain.
SELECT PI.ID_PENGAJUAN,M.NIM,M.NAMA_MAHASISWA,MK.NAMA_MATKUL,JK.KELAS,PI.JENIS_IZIN,PI.TANGGAL_PENGAJUAN
FROM PENGAJUAN_IZIN PI JOIN PRESENSI P ON P.ID_PRESENSI=PI.ID_PRESENSI
JOIN KRS_DETAIL KD ON KD.ID_PENGAMBILAN=P.ID_PENGAMBILAN JOIN JADWAL_KULIAH JK ON JK.ID_JADWAL=KD.ID_JADWAL
JOIN MATA_KULIAH MK ON MK.ID_MATKUL=JK.ID_MATKUL JOIN MAHASISWA M ON M.NIM=PI.NIM_PENGAJU
WHERE JK.NIP_PENGAMPU='198805012020011001' AND PI.STATUS_PENGAJUAN='MENUNGGU';

-- 5. Riwayat pengajuan mahasiswa.
SELECT PI.ID_PENGAJUAN,PI.NIM_PENGAJU,PI.JENIS_IZIN,PI.STATUS_PENGAJUAN,PI.ALASAN_PENOLAKAN
FROM PENGAJUAN_IZIN PI WHERE PI.NIM_PENGAJU='231011024' ORDER BY PI.TANGGAL_PENGAJUAN DESC;

-- 6. Data uji: Bima belum pernah mengajukan; Dimas punya satu pengajuan pending.
SELECT NIM_PENGAJU,COUNT(*) AS JUMLAH_PENGAJUAN FROM PENGAJUAN_IZIN
GROUP BY NIM_PENGAJU ORDER BY NIM_PENGAJU;
