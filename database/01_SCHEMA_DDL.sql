-- PORTAL AKADEMIK - IBM Db2 LUW
-- Jalankan sebagai pemilik schema / user yang memiliki otoritas CREATEIN.
SET CURRENT SCHEMA PORTAL;

CREATE TABLE AKUN_PENGGUNA (
  ID_AKUN VARCHAR(20) NOT NULL,
  EMAIL VARCHAR(120) NOT NULL,
  PASSWORD_HASH VARCHAR(255) NOT NULL,
  PERAN VARCHAR(20) NOT NULL,
  STATUS_AKUN VARCHAR(10) NOT NULL DEFAULT 'AKTIF',
  TANGGAL_DIBUAT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_AKUN_PENGGUNA PRIMARY KEY (ID_AKUN),
  CONSTRAINT UQ_AKUN_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_AKUN_PERAN CHECK (PERAN IN ('MAHASISWA','DOSEN','ADMIN_AKADEMIK')),
  CONSTRAINT CK_AKUN_STATUS CHECK (STATUS_AKUN IN ('AKTIF','NONAKTIF'))
);

CREATE TABLE MAHASISWA (
  NIM VARCHAR(15) NOT NULL,
  ID_AKUN VARCHAR(20) NOT NULL,
  NAMA_MAHASISWA VARCHAR(100) NOT NULL,
  PROGRAM_STUDI VARCHAR(80) NOT NULL,
  ANGKATAN SMALLINT NOT NULL,
  CONSTRAINT PK_MAHASISWA PRIMARY KEY (NIM),
  CONSTRAINT UQ_MHS_AKUN UNIQUE (ID_AKUN),
  CONSTRAINT FK_MHS_AKUN FOREIGN KEY (ID_AKUN) REFERENCES AKUN_PENGGUNA(ID_AKUN)
);

CREATE TABLE DOSEN (
  NIP VARCHAR(20) NOT NULL,
  ID_AKUN VARCHAR(20) NOT NULL,
  NAMA_DOSEN VARCHAR(100) NOT NULL,
  CONSTRAINT PK_DOSEN PRIMARY KEY (NIP),
  CONSTRAINT UQ_DOSEN_AKUN UNIQUE (ID_AKUN),
  CONSTRAINT FK_DOSEN_AKUN FOREIGN KEY (ID_AKUN) REFERENCES AKUN_PENGGUNA(ID_AKUN)
);

CREATE TABLE ADMIN_AKADEMIK (
  ID_ADMIN VARCHAR(20) NOT NULL,
  ID_AKUN VARCHAR(20) NOT NULL,
  NAMA_ADMIN VARCHAR(100) NOT NULL,
  CONSTRAINT PK_ADMIN_AKADEMIK PRIMARY KEY (ID_ADMIN),
  CONSTRAINT UQ_ADMIN_AKUN UNIQUE (ID_AKUN),
  CONSTRAINT FK_ADMIN_AKUN FOREIGN KEY (ID_AKUN) REFERENCES AKUN_PENGGUNA(ID_AKUN)
);

-- Dosen PA adalah relasi bimbingan, bukan role akun yang berbeda.
CREATE TABLE DOSEN_PA (
  NIM VARCHAR(15) NOT NULL,
  NIP VARCHAR(20) NOT NULL,
  TAHUN_AKADEMIK VARCHAR(9) NOT NULL,
  CONSTRAINT PK_DOSEN_PA PRIMARY KEY (NIM, TAHUN_AKADEMIK),
  CONSTRAINT FK_DPA_MHS FOREIGN KEY (NIM) REFERENCES MAHASISWA(NIM),
  CONSTRAINT FK_DPA_DOSEN FOREIGN KEY (NIP) REFERENCES DOSEN(NIP)
);

CREATE TABLE MATA_KULIAH (
  ID_MATKUL VARCHAR(12) NOT NULL,
  NAMA_MATKUL VARCHAR(120) NOT NULL,
  SKS SMALLINT NOT NULL,
  CONSTRAINT PK_MATA_KULIAH PRIMARY KEY (ID_MATKUL),
  CONSTRAINT CK_MK_SKS CHECK (SKS BETWEEN 1 AND 6)
);

CREATE TABLE JADWAL_KULIAH (
  ID_JADWAL VARCHAR(15) NOT NULL,
  ID_MATKUL VARCHAR(12) NOT NULL,
  NIP_PENGAMPU VARCHAR(20) NOT NULL,
  KELAS VARCHAR(15) NOT NULL,
  HARI VARCHAR(10) NOT NULL,
  JAM_MULAI TIME NOT NULL,
  JAM_SELESAI TIME NOT NULL,
  RUANG VARCHAR(30) NOT NULL,
  SEMESTER SMALLINT NOT NULL,
  TAHUN_AKADEMIK VARCHAR(9) NOT NULL,
  CONSTRAINT PK_JADWAL PRIMARY KEY (ID_JADWAL),
  CONSTRAINT UQ_JADWAL_REF UNIQUE (ID_JADWAL, ID_MATKUL),
  CONSTRAINT FK_JADWAL_MK FOREIGN KEY (ID_MATKUL) REFERENCES MATA_KULIAH(ID_MATKUL),
  CONSTRAINT FK_JADWAL_DOSEN FOREIGN KEY (NIP_PENGAMPU) REFERENCES DOSEN(NIP),
  CONSTRAINT CK_JADWAL_SEM CHECK (SEMESTER IN (1,2,3,4,5,6,7,8))
);

CREATE TABLE KRS (
  ID_KRS VARCHAR(15) NOT NULL,
  NIM VARCHAR(15) NOT NULL,
  SEMESTER SMALLINT NOT NULL,
  TAHUN_AKADEMIK VARCHAR(9) NOT NULL,
  STATUS_KRS VARCHAR(15) NOT NULL DEFAULT 'DISETUJUI',
  CONSTRAINT PK_KRS PRIMARY KEY (ID_KRS),
  CONSTRAINT FK_KRS_MHS FOREIGN KEY (NIM) REFERENCES MAHASISWA(NIM),
  CONSTRAINT UQ_KRS_MHS_SEM UNIQUE (NIM, SEMESTER, TAHUN_AKADEMIK)
);

-- ID_PENGAMBILAN adalah identitas unik pengambilan matkul, termasuk saat mengulang.
CREATE TABLE KRS_DETAIL (
  ID_PENGAMBILAN VARCHAR(18) NOT NULL,
  ID_KRS VARCHAR(15) NOT NULL,
  ID_JADWAL VARCHAR(15) NOT NULL,
  CONSTRAINT PK_KRS_DETAIL PRIMARY KEY (ID_PENGAMBILAN),
  CONSTRAINT UQ_KRS_DETAIL_REF UNIQUE (ID_PENGAMBILAN, ID_JADWAL),
  CONSTRAINT FK_KD_KRS FOREIGN KEY (ID_KRS) REFERENCES KRS(ID_KRS),
  CONSTRAINT FK_KD_JADWAL FOREIGN KEY (ID_JADWAL) REFERENCES JADWAL_KULIAH(ID_JADWAL)
);

CREATE TABLE SESI_PRESENSI (
  ID_SESI VARCHAR(18) NOT NULL,
  ID_JADWAL VARCHAR(15) NOT NULL,
  PERTEMUAN_KE SMALLINT NOT NULL,
  TANGGAL DATE NOT NULL,
  BATAS_WAKTU TIMESTAMP,
  STATUS_AKTIF SMALLINT NOT NULL DEFAULT 0,
  TOKEN_QR VARCHAR(100),
  CONSTRAINT PK_SESI PRIMARY KEY (ID_SESI),
  CONSTRAINT UQ_SESI_JADWAL UNIQUE (ID_SESI, ID_JADWAL),
  CONSTRAINT UQ_SESI_PERTEMUAN UNIQUE (ID_JADWAL, PERTEMUAN_KE),
  CONSTRAINT FK_SESI_JADWAL FOREIGN KEY (ID_JADWAL) REFERENCES JADWAL_KULIAH(ID_JADWAL),
  CONSTRAINT CK_SESI_AKTIF CHECK (STATUS_AKTIF IN (0,1))
);

CREATE TABLE PRESENSI (
  ID_PRESENSI VARCHAR(20) NOT NULL,
  ID_SESI VARCHAR(18) NOT NULL,
  ID_PENGAMBILAN VARCHAR(18) NOT NULL,
  ID_JADWAL VARCHAR(15) NOT NULL,
  STATUS_PRESENSI VARCHAR(10) NOT NULL,
  WAKTU_PRESENSI TIMESTAMP,
  CONSTRAINT PK_PRESENSI PRIMARY KEY (ID_PRESENSI),
  CONSTRAINT UQ_PRESENSI_SESI_MHS UNIQUE (ID_SESI, ID_PENGAMBILAN),
  CONSTRAINT FK_PRESENSI_SESI FOREIGN KEY (ID_SESI, ID_JADWAL) REFERENCES SESI_PRESENSI(ID_SESI, ID_JADWAL),
  CONSTRAINT FK_PRESENSI_KRS_DETAIL FOREIGN KEY (ID_PENGAMBILAN, ID_JADWAL) REFERENCES KRS_DETAIL(ID_PENGAMBILAN, ID_JADWAL),
  CONSTRAINT CK_PRESENSI_STATUS CHECK (STATUS_PRESENSI IN ('HADIR','IZIN','SAKIT','ALPHA'))
);

CREATE TABLE PENGAJUAN_IZIN (
  ID_PENGAJUAN VARCHAR(24) NOT NULL,
  ID_PRESENSI VARCHAR(20) NOT NULL,
  NIM_PENGAJU VARCHAR(15) NOT NULL,
  JENIS_IZIN VARCHAR(10) NOT NULL,
  KETERANGAN VARCHAR(1000) NOT NULL,
  FILE_BUKTI VARCHAR(255) NOT NULL,
  STATUS_PENGAJUAN VARCHAR(12) NOT NULL DEFAULT 'MENUNGGU',
  ALASAN_PENOLAKAN VARCHAR(1000),
  TANGGAL_PENGAJUAN TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  NIP_VERIFIKATOR VARCHAR(20),
  TANGGAL_VERIFIKASI TIMESTAMP,
  CONSTRAINT PK_PENGAJUAN PRIMARY KEY (ID_PENGAJUAN),
  CONSTRAINT UQ_PENGAJUAN_PRESENSI UNIQUE (ID_PRESENSI),
  CONSTRAINT FK_PI_PRESENSI FOREIGN KEY (ID_PRESENSI) REFERENCES PRESENSI(ID_PRESENSI),
  CONSTRAINT FK_PI_MHS FOREIGN KEY (NIM_PENGAJU) REFERENCES MAHASISWA(NIM),
  CONSTRAINT FK_PI_VERIFIKATOR FOREIGN KEY (NIP_VERIFIKATOR) REFERENCES DOSEN(NIP),
  CONSTRAINT CK_PI_JENIS CHECK (JENIS_IZIN IN ('IZIN','SAKIT')),
  CONSTRAINT CK_PI_STATUS CHECK (STATUS_PENGAJUAN IN ('MENUNGGU','DISETUJUI','DITOLAK'))
);


CREATE TABLE NOTIFIKASI (
  ID_NOTIFIKASI VARCHAR(24) NOT NULL,
  NIM VARCHAR(15) NOT NULL,
  ID_PENGAJUAN VARCHAR(24) NOT NULL,
  STATUS VARCHAR(12) NOT NULL,
  PESAN VARCHAR(500) NOT NULL,
  TANGGAL_DIBUAT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  DIBACA SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT PK_NOTIFIKASI PRIMARY KEY (ID_NOTIFIKASI),
  CONSTRAINT FK_NOTIFIKASI_MHS FOREIGN KEY (NIM) REFERENCES MAHASISWA(NIM),
  CONSTRAINT FK_NOTIFIKASI_PI FOREIGN KEY (ID_PENGAJUAN) REFERENCES PENGAJUAN_IZIN(ID_PENGAJUAN),
  CONSTRAINT CK_NOTIFIKASI_STATUS CHECK (STATUS IN ('DISETUJUI','DITOLAK','MENUNGGU')),
  CONSTRAINT CK_NOTIFIKASI_DIBACA CHECK (DIBACA IN (0,1))
);

CREATE INDEX IX_NOTIFIKASI_NIM ON NOTIFIKASI(NIM);

CREATE INDEX IX_KRS_NIM ON KRS(NIM);
CREATE INDEX IX_JADWAL_PENGAMPU ON JADWAL_KULIAH(NIP_PENGAMPU);
CREATE INDEX IX_PI_STATUS ON PENGAJUAN_IZIN(STATUS_PENGAJUAN);
CREATE INDEX IX_PI_NIM ON PENGAJUAN_IZIN(NIM_PENGAJU);

COMMIT;
